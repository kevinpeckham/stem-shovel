const byUk = new Map(UK_TO_US.filter(([uk, us]) => uk !== us).map(([uk, us]) => [uk, us]));
const pattern = new RegExp(`\\b(${[...byUk.keys()].join("|")})\\b`, "gi");

/** `text` with every UK spelling in the table replaced by the American one, case kept. */
export function americanize(text: string): string {
	return text.replace(pattern, (word) => keepCase(word, byUk.get(word.toLowerCase()) ?? word));
}

/** The UK words in `text`, in order, each once. */
export function ukWordsIn(text: string): string[] {
	const seen = new Set<string>();
	for (const m of text.matchAll(pattern)) seen.add(m[0]);
	return [...seen];
}

function keepCase(from: string, to: string): string {
	if (from === from.toUpperCase() && from.length > 1) return to.toUpperCase();
	if (from[0] === from[0]!.toUpperCase()) return to[0]!.toUpperCase() + to.slice(1);
	return to;
}
